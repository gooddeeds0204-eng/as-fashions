window.asfGetProducts = function(){
  return Array.isArray(window.ASF_PRODUCTS) ? [...window.ASF_PRODUCTS] : [];
};

window.asfFilterProducts = function(params){
  const p = params || {};
  let list = asfGetProducts();

  if(p.category) list = list.filter(x => x.category.toLowerCase() === String(p.category).toLowerCase());
  if(p.subcategory) list = list.filter(x => x.subcategory.toLowerCase() === String(p.subcategory).toLowerCase());
  if(p.department) list = list.filter(x => x.department.toLowerCase() === String(p.department).toLowerCase());
  if(p.gender) list = list.filter(x => x.gender.toLowerCase() === String(p.gender).toLowerCase());
  if(p.maxPrice != null) list = list.filter(x => Number(x.price) <= Number(p.maxPrice));
  if(p.minDiscount != null) list = list.filter(x => Number(x.discount) >= Number(p.minDiscount));
  if(p.search){
    const q = String(p.search).toLowerCase();
    list = list.filter(x =>
      [x.name,x.brand,x.category,x.department,x.subcategory,...(x.searchTags||[])]
      .join(" ").toLowerCase().includes(q)
    );
  }
  return list;
};
